"""
Контрольные вопросы

1. Почему импульсная характеристика позволяет получить реакцию на произвольный вход?

Любой дискретный входной сигнал можно представить как сумму отдельных импульсов,
сдвинутых по времени и умноженных на значения сигнала:
x[n] = sum(x[k] * delta[n-k]).
Линейная система реагирует на каждый такой импульс как на соответствующую копию
импульсной характеристики h[n]. Поэтому общий выход получается сложением всех
сдвинутых и умноженных копий h[n]. Это выражается формулой свёртки:
y[n] = sum(x[k] * h[n-k]). В zad1.py и zad2.py используется именно эта связь.

2. Как по h[n] получить переходную характеристику?

Переходная характеристика — это реакция системы на единичный скачок u0[n],
который равен нулю до начала отсчётов и единице начиная с n = 0.
Чтобы получить её, нужно выполнить свёртку скачка с импульсной характеристикой:
g[n] = u0[n] * h[n]. Для причинной системы это равносильно накопленной сумме:
g[n] = sum(h[k], k=0..n). В Python такую сумму можно получить через np.cumsum(h).
В zad1.py для системы варианта 1 переходная характеристика стремится к единице.

3. Почему два импульса на входе дают две сдвинутые копии h[n] на выходе?

Линейная система обладает аддитивностью: реакция на сумму сигналов равна сумме
реакций на каждый сигнал отдельно. Благодаря инвариантности к сдвигу импульс
delta[n] вызывает выход h[n], а импульс delta[n-d] вызывает выход h[n-d].
Если второй импульс имеет амплитуду c, его реакция также умножается на c.
Поэтому для входа x[n] = delta[n] + c * delta[n-d] выход равен
y[n] = h[n] + c * h[n-d]. В zad2.py рассматривается случай d = 2 и c = 1.

4. Какие начальные условия использованы при вычислении свёртки?

В zad1.py и zad2.py используются нулевые начальные условия: вход и импульсная
характеристика считаются равными нулю при n < 0. Это соответствует причинным
сигналам и отсутствию накопленного состояния системы до начала расчёта.
Для БИХ-системы в zad3.py функция signal.lfilter без параметра zi также начинает
расчёт с нулевого состояния. Ненулевые начальные условия можно задать через
параметр zi, передав начальные состояния фильтра.
"""

import numpy as np
from scipy import signal

N = 40

h = np.zeros(N)
h[0] = 1

delta = np.zeros(N)
delta[0] = 1

u0 = np.ones(N)

result_impulse = np.convolve(delta, h)[:N]
result_step = np.convolve(u0, h)[:N]
cumulative_h = np.cumsum(h)

print("Проверка свёртки импульса:")
print("np.convolve(delta, h) == h:", np.allclose(result_impulse, h))

print("\nПроверка переходной характеристики:")
print("np.convolve(u0, h) == np.cumsum(h):", np.allclose(result_step, cumulative_h))

b = [0.3]
a = [1, -0.7]

zi = signal.lfilter_zi(b, a) * 2
y_nonzero, zf = signal.lfilter(b, a, u0, zi=zi)

print("\nДемонстрация ненулевого начального условия:")
print(f"Первый выходной отсчёт: {y_nonzero[0]:.6f}")
print(f"Начальное состояние фильтра zi: {zi}")