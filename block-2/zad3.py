import numpy as np


def main():
    print("Переполнение целочисленных типов NumPy\n")

    print(
        f"{'Операция':<12} {'Тип':<8} "
        f"{'Математически':>16} {'NumPy':>12}"
    )
    print("-" * 52)

    rows = [
        (
            "127 + 1",
            "int8",
            128,
            np.int8(127) + np.int8(1),
            "Переполнение: максимум 127 сменяется на -128."
        ),
        (
            "255 + 1",
            "uint8",
            256,
            np.uint8(255) + np.uint8(1),
            "Переполнение: максимум 255 сменяется на 0."
        ),
        (
            "-128 - 1",
            "int8",
            -129,
            np.int8(-128) - np.int8(1),
            "Переполнение: минимум -128 сменяется на 127."
        ),
        (
            "127 + 1",
            "int16",
            128,
            np.int16(127) + np.int16(1),
            "128 входит в диапазон int16."
        ),
        (
            "255 + 1",
            "uint16",
            256,
            np.uint16(255) + np.uint16(1),
            "256 входит в диапазон uint16."
        )
    ]

    for op, typ, expected, actual, note in rows:
        print(
            f"{op:<12} {typ:<8} "
            f"{expected:>16} {str(actual):>12}"
        )
        print("  " + note)

    print("\nДополнительные корректные комбинации:")

    print(
        "127 + 1 с uint8:",
        np.uint8(127) + np.uint8(1)
    )

    print(
        "255 + 1 с int16:",
        np.int16(255) + np.int16(1)
    )

    print(
        "-128 - 1 с uint16: "
        "N/A — отрицательные операнды не представимы uint16."
    )

    print("\nКомбинации с операндом вне диапазона:")

    print(
        "255 + 1 с int8: "
        "N/A — 255 не входит в диапазон int8."
    )

    print(
        "-128 - 1 с uint8: "
        "N/A — отрицательное число не входит в диапазон uint8."
    )

    print("\nВывод:")
    print("Переполнение происходит при выходе результата за диапазон типа.")
    print("В int16 и uint16 приведённые положительные результаты")
    print("помещаются без переполнения.")


if __name__ == "__main__":
    main()