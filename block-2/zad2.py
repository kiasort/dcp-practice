def main():
    numbers = [-128, -127, -2, -1, 0, 1, 2, 127]

    print("Дополнительный код для 8-битных чисел\n")

    print(
        f"{'Десятичное число':>18} "
        f"{'Двоичное представление':>26} {'Знак':>15}"
    )
    print("-" * 62)

    for n in numbers:
        binary = format(n & 0xFF, "08b")

        if n < 0:
            sign = "отрицательный"
        elif n > 0:
            sign = "положительный"
        else:
            sign = "ноль"

        print(f"{n:>18} {binary:>26} {sign:>15}")

    print("\nВывод:")
    print("Отрицательные числа представлены в дополнительном коде.")
    print("Старший бит отрицательного числа равен 1.")


if __name__ == "__main__":
    main()